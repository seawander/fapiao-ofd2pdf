def _text(oid, text, x, y, size, font, deltas, boundary, extra="", codes=None):
    if codes is None:
        delta = " ".join(str(d) for d in deltas)
        codes = (
            f'        <ofd:TextCode X="{x}" Y="{y}" DeltaX="{delta}">{text}</ofd:TextCode>\n'
        )
    return (
        f'      <ofd:TextObject ID="{oid}" Boundary="{boundary}" Font="{font}" '
        f'Size="{size}"{extra}>\n'
        f'        <ofd:FillColor Value="0 0 0"/>\n'
        f"{codes}"
        f"      </ofd:TextObject>\n"
    )


def _vertical(oid, text, boundary, size, font=5):
    """A stacked CJK run: one TextCode, every glyph one em lower (``DeltaY``).

    *boundary* is the top-left of the run, so the first glyph's baseline sits
    at the boundary origin and the rest march down the page, i.e. the text
    reads top to bottom.
    """
    deltas = " ".join(f"{size:g}" for _ in text)
    return (
        f'      <ofd:TextObject ID="{oid}" Boundary="{boundary}" Font="{font}" '
        f'Size="{size}">\n'
        f'        <ofd:FillColor Value="0 0 0"/>\n'
        f'        <ofd:TextCode X="0" Y="0" DeltaY="{deltas}">{text}</ofd:TextCode>\n'
        f"      </ofd:TextObject>\n"
    )


