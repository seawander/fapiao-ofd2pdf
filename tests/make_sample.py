# -- tiny PNG encoder -------------------------------------------------------
def _png_chunk(tag: bytes, data: bytes) -> bytes:
    return (
        struct.pack(">I", len(data))
        + tag
        + data
        + struct.pack(">I", zlib.crc32(tag + data) & 0xFFFFFFFF)
    )


def _make_png(width: int, height: int, pixel) -> bytes:
    raw = bytearray()
    for y in range(height):
        raw.append(0)  # filter type 0
        for x in range(width):
            raw += bytes(pixel(x, y))
    header = struct.pack(">IIBBBBB", width, height, 8, 2, 0, 0, 0)
    return (
        b"\x89PNG\r\n\x1a\n"
        + _png_chunk(b"IHDR", header)
        + _png_chunk(b"IDAT", zlib.compress(bytes(raw), 9))
        + _png_chunk(b"IEND", b"")
    )


def _logo_png() -> bytes:
    size = 32

    def pixel(x: int, y: int):
        edge = x < 2 or y < 2 or x >= size - 2 or y >= size - 2
        if edge:
            return (200, 30, 30)
        if (x // 4 + y // 4) % 2 == 0:
            return (255, 240, 240)
        return (255, 255, 255)

    return _make_png(size, size, pixel)


def _stencil_png() -> bytes:
    """A black five-pointed star on white, painted through ``ImageMask``."""

    size = 24
    cx = cy = (size - 1) / 2.0

    def pixel(x: int, y: int):
        dx, dy = x - cx, y - cy
        radius = math.hypot(dx, dy)
        angle = math.atan2(dy, dx)
        edge = 4.0 + 8.0 * math.cos(5 * angle) * 0.5 + 4.0
        return (0, 0, 0) if radius <= edge else (255, 255, 255)

    return _make_png(size, size, pixel)


